"""Write training/Modelfile with the SYSTEM prompt copied from engine/vibecheck_engine/fixer/prompt.py.

Re-run after changing the prompt so the served model and the training data stay in sync:
    python training/make_modelfile.py --gguf ./vibecheck-coder-Q4_K_M.gguf
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "engine"))
from vibecheck_engine.fixer.prompt import SYSTEM  # noqa: E402

# Mirrors the deepseek-coder-*-instruct chat template that training used (apply_chat_template):
#   <bos>{system}### Instruction:\n{user}\n### Response:\n{answer}\n<|EOT|>\n
# Note there is no newline between the system text and "### Instruction:"; llama.cpp adds <bos>.
TEMPLATE = '''{{ range .Messages }}{{ if eq .Role "system" }}{{ .Content }}{{ else if eq .Role "user" }}### Instruction:
{{ .Content }}
{{ else if eq .Role "assistant" }}### Response:
{{ .Content }}
<|EOT|>
{{ end }}{{ end }}### Response:
'''


def render(gguf: str) -> str:
    if '"""' in SYSTEM:
        raise ValueError("SYSTEM prompt contains triple quotes; escape it for the Modelfile")
    return f'''# Generated by training/make_modelfile.py; edit that script, not this file.
# ollama create vibecheck-coder -f training/Modelfile
FROM {gguf}

TEMPLATE """{TEMPLATE}"""

SYSTEM """{SYSTEM}"""

# Repairs should be deterministic-ish: low temperature, short outputs, stop at end of turn.
PARAMETER temperature 0.1
PARAMETER top_p 0.9
PARAMETER repeat_penalty 1.0
PARAMETER num_ctx 4096
PARAMETER num_predict 1024
PARAMETER stop "<|EOT|>"
PARAMETER stop "### Instruction:"
PARAMETER stop "<｜end▁of▁sentence｜>"

LICENSE """DeepSeek License Agreement applies to the base model weights (deepseek-ai/deepseek-coder-7b-instruct-v1.5).
See https://github.com/deepseek-ai/DeepSeek-Coder/blob/main/LICENSE-MODEL"""
'''


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--gguf", default="./vibecheck-coder-Q4_K_M.gguf")
    ap.add_argument("--out", type=Path, default=HERE / "Modelfile")
    a = ap.parse_args()
    a.out.write_text(render(a.gguf), encoding="utf-8", newline="\n")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
